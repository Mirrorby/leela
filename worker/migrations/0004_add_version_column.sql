-- 0004_add_version_column.sql
--
-- Optimistic concurrency control для games. До этой миграции
-- worker/src/games/repository.ts делал классический read-modify-write:
-- getGameById() читает строку, движок (processRoll) считает новое
-- состояние, updateGame() пишет его обратно — БЕЗ проверки, что строка
-- не изменилась между чтением и записью. При двух параллельных запросах
-- на один и тот же id (например, партия открыта в двух вкладках/устройствах
-- одновременно, или клиент повторяет запрос после таймаута, пока первый
-- всё ещё обрабатывается) один из них тихо перезаписывает результат
-- другого — "потерянное обновление" (lost update), без каких-либо ошибок
-- ни на сервере, ни у пользователя, просто один из бросков молча исчезает
-- из истории партии.
--
-- version — счётчик редакций строки. INSERT всегда пишет version = 1.
-- UPDATE обязан идти с условием WHERE version = <прочитанное значение> и
-- одновременно инкрементировать его (version = version + 1); если UPDATE
-- задел 0 строк — значит, кто-то другой уже сохранил более свежую версию
-- ПОКА мы считали свой ход, и наш результат нужно отбросить, а не
-- применять поверх (см. handleRoll в worker/src/index.ts, возвращает 409).
--
-- DEFAULT 1 — существующие строки на проде (созданные до этой миграции)
-- получают version = 1, как будто это их "нулевая" редакция; следующий
-- UPDATE для них будет ожидать version = 1, что корректно.

ALTER TABLE games ADD COLUMN version INTEGER NOT NULL DEFAULT 1;
